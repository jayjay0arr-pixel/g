// Copies fonts and PDF libraries out of node_modules into www/ so the app works offline.
// Run with:  npm run prepare-web   (after npm install)
import { existsSync, mkdirSync, readdirSync, copyFileSync, writeFileSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nm = (...p) => join(root, "node_modules", ...p);
const www = (...p) => join(root, "www", ...p);

// family name used in the CSS -> fontsource package folder, weights wanted
const FONTS = [
  { family: "Doto", pkg: "doto", weights: [400, 700, 900] },
  { family: "Caveat", pkg: "caveat", weights: [500, 700] },
  { family: "Roboto", pkg: "roboto", weights: [400, 500, 600, 700] },
  { family: "JetBrains Mono", pkg: "jetbrains-mono", weights: [500, 700] },
];
// subsets the app can show (Greek letters matter for formulas)
const RANGES = {
  latin: "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
  "latin-ext": "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
  greek: "U+0370-0377,U+037A-037F,U+0384-038A,U+038C,U+038E-03A1,U+03A3-03FF",
};

rmSync(www("fonts"), { recursive: true, force: true });
mkdirSync(www("fonts"), { recursive: true });
mkdirSync(www("lib"), { recursive: true });

let css = "/* generated by scripts/prepare-web.mjs */\n";
let count = 0;
const problems = [];

for (const f of FONTS) {
  const filesDir = nm("@fontsource", f.pkg, "files");
  if (!existsSync(filesDir)) { problems.push(`missing package @fontsource/${f.pkg}`); continue; }
  const all = readdirSync(filesDir);
  for (const w of f.weights) {
    let gotLatin = false;
    for (const [subset, range] of Object.entries(RANGES)) {
      const name = `${f.pkg}-${subset}-${w}-normal.woff2`;
      if (!all.includes(name)) continue;
      copyFileSync(join(filesDir, name), www("fonts", name));
      css += `@font-face{font-family:"${f.family}";font-style:normal;font-weight:${w};font-display:swap;src:url("${name}") format("woff2");unicode-range:${range}}\n`;
      count++;
      if (subset === "latin") gotLatin = true;
    }
    if (!gotLatin) problems.push(`${f.family} ${w}: no latin file found in @fontsource/${f.pkg}/files`);
  }
}
writeFileSync(www("fonts", "fonts.css"), css);

const libs = [
  [nm("html2canvas", "dist", "html2canvas.min.js"), www("lib", "html2canvas.min.js")],
  [nm("jspdf", "dist", "jspdf.umd.min.js"), www("lib", "jspdf.umd.min.js")],
];
for (const [from, to] of libs) {
  if (existsSync(from)) copyFileSync(from, to);
  else problems.push(`missing ${from.replace(root + "/", "")}`);
}

console.log(`fonts: ${count} font files copied, fonts.css written`);
if (problems.length) {
  console.error("PROBLEMS:\n - " + problems.join("\n - "));
  process.exit(1);
}
console.log("libs: html2canvas + jspdf copied. Offline assets ready.");
